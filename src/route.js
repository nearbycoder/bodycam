export const duration = marks.at(-1)[0];
export function routeAt(t){
  const i=marks.findIndex(m=>m[0]>t);
  if(i<0) return marks.at(-1).slice(1);
  const a=marks[Math.max(0,i-1)],b=marks[i],prev=marks[Math.max(0,i-2)],next=marks[Math.min(marks.length-1,i+1)];
  const dt=b[0]-a[0], u=dt?(t-a[0])/dt:0, u2=u*u,u3=u2*u;
  return a.slice(1).map((v,j)=>{
    const k=j+1;
    const d0=(b[k]-prev[k])/(b[0]-prev[0]||1)*dt;
    const d1=(next[k]-a[k])/(next[0]-a[0]||1)*dt;
    return (2*u3-3*u2+1)*v+(u3-2*u2+u)*d0+(-2*u3+3*u2)*b[k]+(u3-u2)*d1;
  });
}
